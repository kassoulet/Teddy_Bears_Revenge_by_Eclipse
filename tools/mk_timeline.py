#!/usr/bin/env python3
"""mk_timeline.py: row start times (order,row -> seconds) of TEDDY.MOD as libopenmpt plays it (the web player uses the same library).
Renders the module in 64-sample chunks and records each (order,row) change. Writes re/timeline.json and web/timeline.js."""
import ctypes,json,os
H=os.path.dirname(os.path.abspath(__file__)); L=ctypes.CDLL('libopenmpt.so.0'); P=ctypes.c_void_p
d=open(H+'/../web/TEDDY.MOD','rb').read()
L.openmpt_module_create_from_memory2.restype=P; L.openmpt_module_create_from_memory2.argtypes=[ctypes.c_char_p,ctypes.c_size_t]+[P]*7
L.openmpt_module_read_mono.argtypes=[P,ctypes.c_int32,ctypes.c_size_t,ctypes.POINTER(ctypes.c_int16)]; L.openmpt_module_read_mono.restype=ctypes.c_size_t
L.openmpt_module_get_current_order.argtypes=[P]; L.openmpt_module_get_current_row.argtypes=[P]
L.openmpt_module_get_order_pattern.argtypes=[P,ctypes.c_int32]
L.openmpt_module_set_repeat_count.argtypes=[P,ctypes.c_int32]
m=L.openmpt_module_create_from_memory2(d,len(d),None,None,None,None,None,None,None)
L.openmpt_module_set_repeat_count(m,0)
buf=(ctypes.c_int16*64)(); SR=44100; rows=[]; n=0; last=None
while True:
    got=L.openmpt_module_read_mono(m,SR,64,buf)
    if got==0: break
    k=(L.openmpt_module_get_current_order(m),L.openmpt_module_get_current_row(m))
    if last and k[0]<last[0]: break   # module restarts: end of the song
    if k!=last:
        rows.append([k[0],L.openmpt_module_get_order_pattern(m,k[0]),k[1],round(n/SR,4)]); last=k
    n+=got
dur=round(rows[-1][3]+0.06,3)  # last row (order 34 row 63) ends ~0.06 s later
json.dump({'rows':rows,'duration':dur},open(H+'/../re/timeline.json','w'))
open(H+'/../web/timeline.js','w').write('// generated by tools/mk_timeline.py - do not edit\nexport const DUR=%s;\nexport const ROWS=%s;\n'%(dur,json.dumps(rows,separators=(',',':'))))
print(len(rows),'rows, duration',dur,'last',rows[-1],'orders',max(r[0] for r in rows)+1)
